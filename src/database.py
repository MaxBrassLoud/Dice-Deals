"""Datenzugriff fuer Dice Deals auf Supabase PostgreSQL.

Alle Funktionen halten die gleiche API wie das frühere SQLite-Modul, damit
app.py weitgehend unverändert bleibt. Neu:

* users.auth_provider : 'legacy' | 'supabase' | 'discord'
* users.auth_uid      : Supabase-Auth-UUID bei auth_provider='supabase'

Passwörter werden nicht mehr lokal gehasst, sobald ein Konto auf Supabase
Auth umgestellt ist; Legacy-Hashes bleiben bis zur ersten Anmeldung lesbar.
"""

import os
import secrets
import time

import psycopg
import psycopg.errors as pgerr


def _dsn():
    dsn = os.getenv("SUPABASE_DB_URL")
    if not dsn:
        raise RuntimeError("SUPABASE_DB_URL ist nicht gesetzt (Postgres-Verbindung von Supabase)")
    return dsn


def get_connection():
    return psycopg.connect(_dsn(), connect_timeout=10)


USER_COLUMNS = (
    "id, username, password, email, third_party, provider, user_id, "
    "avatar_emoji, avatar_color, last_seen, discord_id, discord_avatar, "
    "discord_username, current_room_code, avatar_url, display_name, "
    "auth_provider, auth_uid"
)


def create_database():
    with get_connection() as conn:
        c = conn.cursor()
        c.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id TEXT PRIMARY KEY,
            username TEXT UNIQUE,
            password TEXT,
            email TEXT UNIQUE,
            third_party INTEGER,
            provider INTEGER,
            user_id TEXT,
            avatar_emoji TEXT DEFAULT '🎲',
            avatar_color TEXT DEFAULT '#3b82f6',
            last_seen REAL DEFAULT 0,
            discord_id TEXT,
            discord_avatar TEXT,
            discord_username TEXT,
            current_room_code TEXT,
            avatar_url TEXT,
            display_name TEXT,
            auth_provider TEXT DEFAULT 'legacy',
            auth_uid TEXT UNIQUE
        )
        """)
        # Spalten für Bestands-Datenbanken, die schon ohne sie angelegt wurden.
        c.execute("SELECT column_name FROM information_schema.columns WHERE table_name = 'users'")
        columns = {row[0] for row in c.fetchall()}
        if "auth_provider" not in columns:
            c.execute("ALTER TABLE users ADD COLUMN auth_provider TEXT DEFAULT 'legacy'")
        if "auth_uid" not in columns:
            c.execute("ALTER TABLE users ADD COLUMN auth_uid TEXT UNIQUE")

        c.execute("""
        CREATE TABLE IF NOT EXISTS friendships (
            user_id TEXT NOT NULL,
            friend_id TEXT NOT NULL,
            status TEXT DEFAULT 'pending',
            created_at REAL,
            PRIMARY KEY (user_id, friend_id)
        )
        """)

        c.execute("""
        CREATE TABLE IF NOT EXISTS friend_invites (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            inviter_id TEXT NOT NULL,
            invitee_id TEXT NOT NULL,
            room_code TEXT NOT NULL,
            created_at REAL
        )
        """)

        c.execute("""
        CREATE TABLE IF NOT EXISTS games (
            room_code TEXT PRIMARY KEY,
            state TEXT NOT NULL,
            updated_at REAL,
            last_activity REAL
        )
        """)

        c.execute("""
        CREATE TABLE IF NOT EXISTS auth_tokens (
            token TEXT PRIMARY KEY,
            user_id TEXT NOT NULL,
            created_at REAL,
            last_used REAL
        )
        """)
        conn.commit()


def create_user(user_id, username, password, email, third_party=0, provider=0, ext_user_id=None,
                auth_provider="legacy", auth_uid=None):
    with get_connection() as conn:
        try:
            with conn.cursor() as c:
                c.execute("""
                INSERT INTO users (id, username, password, email, third_party, provider, user_id,
                                   auth_provider, auth_uid)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
                """, (user_id, username, password, email, third_party, provider, ext_user_id,
                      auth_provider, auth_uid))
            conn.commit()
            return True
        except (pgerr.UniqueViolation, pgerr.NotNullViolation):
            conn.rollback()
            return False


