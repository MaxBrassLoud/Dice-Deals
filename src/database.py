def send_friend_request(user_id, friend_id):
    with get_connection() as conn:
        with conn.cursor() as c:
            c.execute("SELECT status FROM friendships WHERE user_id = %s AND friend_id = %s", (friend_id, user_id))
            existing = c.fetchone()
            if existing and existing[0] == "accepted":
                return False, "Bereits befreundet"
            if existing and existing[0] == "pending":
                c.execute("UPDATE friendships SET status = 'accepted' WHERE user_id = %s AND friend_id = %s",
                          (friend_id, user_id))
                c.execute("""
                    INSERT INTO friendships (user_id, friend_id, status, created_at)
                    VALUES (%s, %s, 'accepted', %s)
                    ON CONFLICT (user_id, friend_id) DO UPDATE SET status = 'accepted', created_at = EXCLUDED.created_at
                """, (user_id, friend_id, time.time()))
                conn.commit()
                return True, "Freundschaft angenommen"
            c.execute("""
                INSERT INTO friendships (user_id, friend_id, status, created_at)
                VALUES (%s, %s, 'pending', %s)
                ON CONFLICT (user_id, friend_id) DO UPDATE SET status = 'pending', created_at = EXCLUDED.created_at
            """, (user_id, friend_id, time.time()))
            conn.commit()
            return True, "Freundschaftsanfrage gesendet"


