def _linked_accounts_from(raw):
    """Liest einen linked_accounts-Wert (JSON-Text) als Liste; leerer/ungültiger Wert -> []."""
    if not raw:
        return []
    try:
        import json as _json
        value = _json.loads(raw)
        return value if isinstance(value, list) else []
    except (ValueError, TypeError):
        return []


def create_database():
    with get_connection() as conn:
        c = conn.cursor()
        # Tabelle ohne Passwort, E-Mail und Discord-Legacy-Spalten
        c.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
            username TEXT UNIQUE,
            current_room_code TEXT,
            avatar_url TEXT,
            display_name TEXT,
            auth_provider TEXT DEFAULT 'legacy',
            auth_uid TEXT UNIQUE,
            avatar_style TEXT DEFAULT 'diagonal',
            avatar_emoji TEXT DEFAULT '🎲',
            avatar_color TEXT DEFAULT '#3b82f6',
            last_seen REAL DEFAULT 0,
            bio TEXT,
            status_text TEXT,
            show_last_seen BOOLEAN DEFAULT true,
            show_in_search BOOLEAN DEFAULT true,
            allow_friend_requests BOOLEAN DEFAULT true,
            linked_accounts TEXT DEFAULT '[]'
        )
        """)

        c.execute("""
        CREATE TABLE IF NOT EXISTS friendships (
            user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            friend_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            status TEXT DEFAULT 'pending',
            created_at REAL,
            PRIMARY KEY (user_id, friend_id)
        )
        """)

        c.execute("""
        CREATE TABLE IF NOT EXISTS friend_invites (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            inviter_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            invitee_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            room_code TEXT NOT NULL,
            created_at REAL
        )
        """)

        c.execute("""
        CREATE TABLE IF NOT EXISTS games (
            room_code TEXT PRIMARY KEY,
            state TEXT NOT NULL,
            updated_at REAL,
            last_activity REAL
        )
        """)

        c.execute("""
        CREATE TABLE IF NOT EXISTS auth_tokens (
            token TEXT PRIMARY KEY,
            user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            created_at REAL,
            last_used REAL
        )
        """)
        conn.commit()


def create_user(auth_uid, username, auth_provider="supabase"):
    """Erstellt einen neuen User in public.users.
    Die ID ist exakt die Supabase UUID (auth_uid).
    """
    with get_connection() as conn:
        try:
            with conn.cursor() as c:
                c.execute("""
                INSERT INTO users (id, username, auth_provider, auth_uid)
                VALUES (%s, %s, %s, %s)
                """, (auth_uid, username, auth_provider, auth_uid))
                conn.commit()
                return True
        except (pgerr.UniqueViolation, pgerr.NotNullViolation):
            conn.rollback()
            return False


